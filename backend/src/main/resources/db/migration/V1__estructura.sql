CREATE TABLE usuarios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(100) NOT NULL,
 email VARCHAR(180) NOT NULL UNIQUE,
 clave VARCHAR(100) NOT NULL,
 rol VARCHAR(20) NOT NULL CHECK (rol IN ('ADMINISTRADOR','OPERADOR')),
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE contenidos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tipo VARCHAR(24) NOT NULL CHECK (tipo IN ('CARRUSEL','PROYECTO','CASA_MODELO','RECREACION','TESTIMONIO','VENTAS','NOSOTROS')),
 titulo VARCHAR(160) NOT NULL,
 subtitulo VARCHAR(240) NOT NULL DEFAULT '',
 descripcion TEXT NOT NULL DEFAULT '',
 imagen VARCHAR(300) NOT NULL,
 imagen_secundaria VARCHAR(300) NOT NULL DEFAULT '',
 contacto VARCHAR(160) NOT NULL DEFAULT '',
 cargo VARCHAR(100) NOT NULL DEFAULT '',
 calificacion INTEGER NOT NULL DEFAULT 5 CHECK (calificacion BETWEEN 1 AND 5),
 orden INTEGER NOT NULL DEFAULT 0 CHECK (orden >= 0),
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_contenidos_tipo_orden ON contenidos(tipo, activo, orden, id);
CREATE TABLE secciones (
 codigo VARCHAR(24) PRIMARY KEY,
 titulo VARCHAR(160) NOT NULL,
 subtitulo VARCHAR(240) NOT NULL,
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 version BIGINT NOT NULL DEFAULT 0
);
