CREATE TABLE configuracion (
 id INTEGER PRIMARY KEY CHECK (id=1),
 nombre VARCHAR(100) NOT NULL,
 lema VARCHAR(240) NOT NULL,
 telefono VARCHAR(40) NOT NULL DEFAULT '',
 correo VARCHAR(180) NOT NULL DEFAULT '',
 direccion VARCHAR(300) NOT NULL DEFAULT '',
 horario VARCHAR(160) NOT NULL DEFAULT '',
 mapa VARCHAR(500) NOT NULL DEFAULT '',
 facebook VARCHAR(300) NOT NULL DEFAULT '',
 instagram VARCHAR(300) NOT NULL DEFAULT '',
 whatsapp VARCHAR(30) NOT NULL DEFAULT '',
 version BIGINT NOT NULL DEFAULT 0
);
