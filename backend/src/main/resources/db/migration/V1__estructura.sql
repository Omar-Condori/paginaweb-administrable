CREATE TABLE archivos (
 nombre VARCHAR(80) PRIMARY KEY,
 original VARCHAR(240) NOT NULL,
 mime VARCHAR(40) NOT NULL,
 bytes BIGINT NOT NULL,
 creado TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
