-- Proyectos: estado (en ejecución / terminado / próximamente), fecha y varias fotografías por tarjeta.
ALTER TABLE contenidos ADD COLUMN estado VARCHAR(20) NOT NULL DEFAULT ''
    CHECK (estado IN ('', 'EN_EJECUCION', 'TERMINADO', 'PROXIMAMENTE'));
ALTER TABLE contenidos ADD COLUMN fecha VARCHAR(10) NOT NULL DEFAULT '';

CREATE TABLE contenido_imagenes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contenido_id BIGINT NOT NULL REFERENCES contenidos(id) ON DELETE CASCADE,
    imagen VARCHAR(300) NOT NULL,
    orden INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX idx_contenido_imagenes ON contenido_imagenes(contenido_id, orden, id);
